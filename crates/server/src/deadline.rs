//! Request deadlines on every route (ADR 0058). `server.request_timeout`
//! bounds a request answered whole and `server.stream_timeout` one that
//! streams, each counted from the request's admission (an image job's from
//! its start, never from its queue); `0` is no deadline. What a passed
//! deadline answers is `server.timeout_reply`: the answer so far, ended as a
//! length limit ends one (`partial`), or an error (`error`). A decision's
//! question and an image job are answered an error either way: neither has a
//! partial answer.

use std::time::Duration;

use axum::http::{HeaderName, HeaderValue};
use axum::response::Response;

/// What a request past its deadline is answered (`--server-timeout-reply`,
/// ADR 0058).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum TimeoutReply {
    /// What was generated by then, as an answer a length limit cut: chat
    /// completions' `finish_reason: "length"`, the Responses API's
    /// `status: "incomplete"` with `incomplete_details.reason:
    /// "max_output_tokens"` — the only standard way either says "cut by a
    /// limit", which every client already reads.
    #[default]
    Partial,
    /// An error: `504 request_timeout` for an answer not yet sent, a stream's
    /// error ending for one that already answered `200`.
    Error,
}

impl TimeoutReply {
    /// Every value, in the order `--help` and errors list them.
    pub const ALL: [Self; 2] = [Self::Partial, Self::Error];

    /// The value's name on the command line.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Partial => "partial",
            Self::Error => "error",
        }
    }
}

/// How far ahead a request with no deadline is held to: a decade, which no
/// request outlives. An instant rather than none keeps every timer one shape
/// (`timeout_at`, `sleep_until`) whichever the setting.
const NO_DEADLINE: Duration = Duration::from_secs(10 * 365 * 24 * 3600);

/// The instant a request given `timeout` from now must end by; a zero
/// `timeout` is no deadline (ADR 0058).
pub fn after(timeout: Duration) -> tokio::time::Instant {
    tokio::time::Instant::now() + if timeout.is_zero() { NO_DEADLINE } else { timeout }
}

/// The header a non-streaming answer its deadline cut carries, spelled as
/// `x-ignis-class` is: `x-ignis-stopped-by: request_timeout`. A streamed one
/// sent its headers before the deadline passed, and the request log's
/// `ignis.request.cancelled` line says `timeout` for both.
pub const STOPPED_BY: &str = "x-ignis-stopped-by";

/// `response`, marked as cut by its deadline ([`STOPPED_BY`]).
pub fn stopped_by_timeout(mut response: Response) -> Response {
    response.headers_mut().insert(HeaderName::from_static(STOPPED_BY), HeaderValue::from_static("request_timeout"));
    response
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_zero_timeout_is_no_deadline_and_any_other_counts_from_now() {
        let now = tokio::time::Instant::now();
        assert!(after(Duration::ZERO) > now + Duration::from_secs(365 * 24 * 3600), "zero is no deadline");
        let soon = after(Duration::from_secs(2));
        assert!(soon >= now + Duration::from_secs(2) && soon < now + Duration::from_secs(60));
    }
}
