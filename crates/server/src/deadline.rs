//! Request deadlines on every route (ADR 0058). `server.request_timeout`
//! bounds a request answered whole and `server.stream_timeout` one that
//! streams, each counted from the request's admission (an image job's from
//! its start, never from its queue); `0` is no deadline. What a passed
//! deadline answers is `server.timeout_reply`: the answer so far, ended as a
//! length limit ends one (`partial`), or an error (`error`). A decision's
//! question and an image job are answered an error either way: neither has a
//! partial answer.

use std::future::Future;
use std::pin::Pin;
use std::task::{Context, Poll};
use std::time::Duration;

use axum::http::{HeaderName, HeaderValue};
use axum::response::{IntoResponse, Response};
use ignis_core::{SchedEvent, TokenId};

use crate::api::CancelOnDrop;
use crate::engine::{drain_tokens, EventStream};
use crate::loop_guard::Running;

/// What a request past its deadline is answered (`--server-timeout-reply`,
/// ADR 0058).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum TimeoutReply {
    /// What was generated by then, as an answer a length limit cut: chat
    /// completions' `finish_reason: "length"`, the Responses API's
    /// `status: "incomplete"` with `incomplete_details.reason:
    /// "max_output_tokens"` — the only standard way either says "cut by a
    /// limit", which every client already reads.
    #[default]
    Partial,
    /// An error: `504 request_timeout` for an answer not yet sent, a stream's
    /// error ending for one that already answered `200`.
    Error,
}

impl TimeoutReply {
    /// Every value, in the order `--help` and errors list them.
    pub const ALL: [Self; 2] = [Self::Partial, Self::Error];

    /// The value's name on the command line.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Partial => "partial",
            Self::Error => "error",
        }
    }
}

/// How far ahead a request with no deadline is held to: a decade, which no
/// request outlives. An instant rather than none keeps every timer one shape
/// (`timeout_at`, `sleep_until`) whichever the setting.
const NO_DEADLINE: Duration = Duration::from_secs(10 * 365 * 24 * 3600);

/// The instant a request given `timeout` from now must end by; a zero
/// `timeout` is no deadline (ADR 0058).
pub fn after(timeout: Duration) -> tokio::time::Instant {
    tokio::time::Instant::now() + if timeout.is_zero() { NO_DEADLINE } else { timeout }
}

/// The deadline a request is held to: how long, and whether it is the one
/// of a request that streams. Where a request's being streamed picks
/// `server.stream_timeout` over `server.request_timeout`, and where every
/// `request_timeout` error is worded ([`Timeout::error`]). A zero `duration`
/// is none.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Timeout {
    pub duration: Duration,
    pub streamed: bool,
}

impl Timeout {
    /// No deadline.
    pub const NONE: Self = Self { duration: Duration::ZERO, streamed: false };

    /// The deadline `live` holds a request to: `stream_timeout` when it
    /// streams, `request_timeout` when it is answered whole.
    pub fn of(live: &crate::Live, streamed: bool) -> Self {
        let duration = if streamed { live.stream_timeout } else { live.request_timeout };
        Self { duration, streamed }
    }

    /// The instant it passes, counted from now ([`after`]).
    pub fn from_now(self) -> tokio::time::Instant {
        after(self.duration)
    }

    /// What a request past it is told: the deadline that passed and the flag
    /// that raises it (GitHub #95), so an operator reading the error does
    /// not suspect a wedged engine when a healthy one just needed longer.
    pub fn message(self) -> String {
        let (what, flag, env) = match self.streamed {
            true => ("stream", "--server-stream-timeout", "IGNIS_SERVER_STREAM_TIMEOUT"),
            false => ("request", "--server-request-timeout", "IGNIS_SERVER_REQUEST_TIMEOUT"),
        };
        format!(
            "the {what} did not complete within the server's {}s timeout (the engine may be wedged) — raise it with {flag}/{env}",
            self.duration.as_secs()
        )
    }

    /// The `request_timeout` error body: a `504`'s, and the error a stream
    /// that already answered `200` ends with.
    pub(crate) fn error(self) -> crate::api::ApiError {
        crate::api::ApiError::new("request_timeout", "request_timeout", &self.message())
    }

    /// The `504 request_timeout` of a request answered whole.
    pub(crate) fn response(self) -> Response {
        (axum::http::StatusCode::GATEWAY_TIMEOUT, axum::Json(self.error())).into_response()
    }
}

/// The header a non-streaming answer its deadline cut carries:
/// `ignis-stopped-by: request_timeout`, spelled as the server's other custom
/// response header is, `ignis-model-status` (`/v1/config`), with no `x-`.
/// A streamed one sent its headers before the deadline passed, and the
/// request log's `ignis.request.cancelled` line says `timeout` for both.
/// Exposed to a browser on another origin (`api::cors_headers`).
pub const STOPPED_BY: &str = "ignis-stopped-by";

/// `response`, marked as cut by its deadline ([`STOPPED_BY`]).
pub fn stopped_by_timeout(mut response: Response) -> Response {
    response.headers_mut().insert(HeaderName::from_static(STOPPED_BY), HeaderValue::from_static("request_timeout"));
    response
}

/// A streamed answer's deadline (`server.stream_timeout`), the chat
/// completions stream's and the Responses one's: past it the request is
/// cancelled, the loop guard sends what it held back (ADR 0052), and the
/// answer ends after the tokens it was still owed ([`poll_next_event`]).
pub(crate) struct StreamDeadline {
    /// The engine request generating, which a passed deadline stops.
    running: Running,
    sleep: Pin<Box<tokio::time::Sleep>>,
    timeout: Timeout,
    reply: TimeoutReply,
    /// The deadline passed and the loop guard sends what it held back: the
    /// stream's end ends the answer.
    stopping: bool,
}

impl StreamDeadline {
    /// `timeout` from now, on the engine request `running` names, answered
    /// as `reply` says; none for a zero `timeout`.
    pub(crate) fn after(timeout: Timeout, running: Running, reply: TimeoutReply) -> Option<Self> {
        let sleep = || Box::pin(tokio::time::sleep(timeout.duration));
        (!timeout.duration.is_zero()).then(|| Self { running, sleep: sleep(), timeout, reply, stopping: false })
    }

    fn passed(&self, owed: Vec<TokenId>) -> Next {
        Next::Passed { owed, reply: self.reply, timeout: self.timeout }
    }
}

/// What a streamed answer handles next ([`poll_next_event`]).
pub(crate) enum Next {
    /// One of the request's events; past the deadline, only a token.
    Event(SchedEvent),
    /// The request's stream closed before its deadline passed.
    Closed,
    /// The deadline passed and the request was cancelled: the answer ends
    /// after `owed`, the last tokens it was owed, as `reply` says.
    Passed { owed: Vec<TokenId>, reply: TimeoutReply, timeout: Timeout },
}

/// The next of a streamed answer's events — `held` first, the event that
/// ended the last run of tokens — held to `deadline` when it has one.
///
/// The deadline is checked before every event, for the reason
/// `responses::drive` checks it first. Once it passed, the request is
/// cancelled, then a loop guard sends what it held back and ends its stream:
/// its tokens still come, any other event is the request's own end and no
/// longer counts, and the stream's end is [`Next::Passed`]. With no guard,
/// the tokens already waiting on `stream` are the last, never one more.
pub(crate) fn poll_next_event(
    mut deadline: Option<&mut StreamDeadline>,
    cx: &mut Context<'_>,
    cancel: &mut CancelOnDrop,
    stream: &mut EventStream,
    held: &mut Option<SchedEvent>,
) -> Poll<Next> {
    loop {
        if let Some(deadline) = deadline.as_deref_mut().filter(|deadline| !deadline.stopping) {
            if deadline.sleep.as_mut().poll(cx).is_ready() {
                // Cancelled now, for its deadline: before a guard is stopped,
                // whose own cancel would log its consumer letting it go.
                cancel.timed_out();
                if deadline.running.stop() {
                    deadline.stopping = true;
                } else {
                    let mut owed = Vec::new();
                    let _ = drain_tokens(stream, &mut owed);
                    *held = None;
                    return Poll::Ready(deadline.passed(owed));
                }
            }
        }
        let stopping = deadline.as_deref().filter(|deadline| deadline.stopping);
        let polled = match held.take() {
            Some(event) => Poll::Ready(Some(event)),
            None => stream.poll_recv(cx),
        };
        return match (polled, stopping) {
            (Poll::Pending, _) => Poll::Pending,
            (Poll::Ready(Some(token @ SchedEvent::Token { .. })), _) => Poll::Ready(Next::Event(token)),
            // Past the deadline only the tokens still count.
            (Poll::Ready(Some(_)), Some(_)) => continue,
            (Poll::Ready(Some(event)), None) => Poll::Ready(Next::Event(event)),
            // Everything the guard held back went out: the deadline's end.
            (Poll::Ready(None), Some(deadline)) => Poll::Ready(deadline.passed(Vec::new())),
            (Poll::Ready(None), None) => Poll::Ready(Next::Closed),
        };
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_zero_timeout_is_no_deadline_and_any_other_counts_from_now() {
        let now = tokio::time::Instant::now();
        assert!(after(Duration::ZERO) > now + Duration::from_secs(365 * 24 * 3600), "zero is no deadline");
        let soon = after(Duration::from_secs(2));
        assert!(soon >= now + Duration::from_secs(2) && soon < now + Duration::from_secs(60));
    }

    /// A request is held to the stream's deadline when it streams and to the
    /// whole answer's otherwise, and its `request_timeout` error names the
    /// one that passed and the flag that raises it.
    #[tokio::test]
    async fn a_timeout_is_the_stream_s_or_the_whole_answer_s_and_its_error_names_it() {
        let live = crate::Live { request_timeout: Duration::from_secs(30), stream_timeout: Duration::from_secs(60), ..crate::Live::default() };
        let streamed = Timeout::of(&live, true);
        let whole = Timeout::of(&live, false);
        assert_eq!((streamed.duration, whole.duration), (Duration::from_secs(60), Duration::from_secs(30)));
        assert!(streamed.message().contains("60s timeout") && streamed.message().contains("--server-stream-timeout/IGNIS_SERVER_STREAM_TIMEOUT"));
        assert!(whole.message().contains("30s timeout") && whole.message().contains("--server-request-timeout/IGNIS_SERVER_REQUEST_TIMEOUT"));
        let response = whole.response();
        assert_eq!(response.status(), axum::http::StatusCode::GATEWAY_TIMEOUT);
        let body = axum::body::to_bytes(response.into_body(), usize::MAX).await.unwrap();
        let body: serde_json::Value = serde_json::from_slice(&body).unwrap();
        assert_eq!((&body["error"]["type"], &body["error"]["code"]), (&serde_json::json!("request_timeout"), &serde_json::json!("request_timeout")));
        assert_eq!(body["error"]["message"], whole.message());
    }
}
